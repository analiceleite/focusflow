export type ResolvedIcon = { kind: 'pixel'; name: PixelIconName } | { kind: 'letter' };

/** Resolve o ícone salvo de uma atividade: "px:<id>", emoji conhecido ou fallback de letra. */
export function resolveActivityIcon(raw: string | null | undefined): ResolvedIcon {
  const value = (raw ?? '').trim();
  if (value.startsWith(PIXEL_ICON_PREFIX)) {
    const id = value.slice(PIXEL_ICON_PREFIX.length);
    if (id in ICON_ROWS) return { kind: 'pixel', name: id };
  }
  // Remove seletores de variação (U+FE0F) e tons de pele antes de procurar
  const key = value.replace(/️/g, '').replace(/[\u{1F3FB}-\u{1F3FF}]/gu, '');
  const mapped = EMOJI_MAP[key];
  return mapped ? { kind: 'pixel', name: mapped } : { kind: 'letter' };
}

const cache = new Map<string, Sprite>();

export function pixelIconSprite(name: PixelIconName): Sprite | null {
  const rows = ICON_ROWS[name];
  if (!rows) return null;
  let sprite = cache.get(name);
  if (!sprite) {
    sprite = buildSprite(rows, ICON_PALETTE);
    cache.set(name, sprite);
  }
  return sprite;
}

/** Desenha um ícone pixel num canvas (usado pela janela PiP). */
export function drawPixelIcon(
  ctx: CanvasRenderingContext2D,
  name: PixelIconName,
  cx: number,
  cy: number,
  size: number
): void {
  const sprite = pixelIconSprite(name);
  if (!sprite) return;
  const unit = Math.max(1, Math.floor(size / sprite.width));
  const x0 = Math.round(cx - (sprite.width * unit) / 2);
  const y0 = Math.round(cy - (sprite.height * unit) / 2);
  for (const p of sprite.pixels) {
    ctx.fillStyle = p.fill;
    ctx.fillRect(x0 + p.x * unit, y0 + p.y * unit, unit, unit);
  }
}
